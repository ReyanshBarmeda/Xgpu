using System.Text;
using System.Text.Json;

namespace Xdos.Host;

internal static class Codegen
{
    public static int Run(string root)
    {
        var abiPath = Path.Combine(root, "userland", "abi", "syscall_numbers.json");
        var tokensPath = Path.Combine(root, "userland", "design", "tokens.json");
        var abi = JsonDocument.Parse(File.ReadAllText(abiPath));

        EmitSyscalls(root, abi);
        EmitTheme(root, tokensPath);
        Console.WriteLine("[xdos] codegen ok");
        return 0;
    }

    static void EmitSyscalls(string root, JsonDocument abi)
    {
        var syscalls = abi.RootElement.GetProperty("syscalls");
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated — run: dotnet run --project userland/host/Xdos.Host -- codegen>");
        sb.AppendLine("namespace Xdos.Abstractions;");
        sb.AppendLine();
        sb.AppendLine("public static partial class SyscallNumbers");
        sb.AppendLine("{");
        foreach (var sc in syscalls.EnumerateArray())
        {
            var name = sc.GetProperty("name").GetString()!;
            var num = sc.GetProperty("number").GetInt32();
            sb.AppendLine($"    public const int {Pascal(name)} = {num};");
        }
        sb.AppendLine("}");

        sb.AppendLine();
        sb.AppendLine("public static partial class Syscall");
        sb.AppendLine("{");
        sb.AppendLine("    /// <summary>Host stub — on Xdos, link userland/apps/*/syscall_shim.asm instead.</summary>");
        sb.AppendLine("    public static long Invoke(ulong number, ulong a1 = 0, ulong a2 = 0, ulong a3 = 0, ulong a4 = 0, ulong a5 = 0, ulong a6 = 0)");
        sb.AppendLine("        => throw new PlatformNotSupportedException(\"Syscall.Invoke runs only on Xdos userland binaries.\");");
        sb.AppendLine();

        foreach (var sc in syscalls.EnumerateArray())
        {
            var name = sc.GetProperty("name").GetString()!;
            switch (name)
            {
                case "write":
                    sb.AppendLine("    public static long Write(int fd, ReadOnlySpan<byte> buffer)");
                    sb.AppendLine("    {");
                    sb.AppendLine("        fixed (byte* p = buffer)");
                    sb.AppendLine("            return Invoke(SyscallNumbers.Write, (ulong)fd, (ulong)p, (ulong)buffer.Length);");
                    sb.AppendLine("    }");
                    break;
                case "read":
                    sb.AppendLine("    public static long Read() => Invoke(SyscallNumbers.Read);");
                    break;
                case "yield":
                    sb.AppendLine("    public static long Yield() => Invoke(SyscallNumbers.Yield);");
                    break;
                case "exit":
                    sb.AppendLine("    public static void Exit(int code) => Invoke(SyscallNumbers.Exit, (ulong)code);");
                    break;
                case "getpid":
                    sb.AppendLine("    public static long GetPid() => Invoke(SyscallNumbers.Getpid);");
                    break;
            }
        }

        sb.AppendLine("}");

        var outDir = Path.Combine(root, "userland", "host", "Xdos.Host", "Generated");
        Directory.CreateDirectory(outDir);
        var outPath = Path.Combine(outDir, "Syscall.generated.cs");
        File.WriteAllText(outPath, sb.ToString());
        Console.WriteLine($"  wrote {Path.GetRelativePath(root, outPath)}");
    }

    static void EmitTheme(string root, string tokensPath)
    {
        var json = File.ReadAllText(tokensPath);
        using var doc = JsonDocument.Parse(json);
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated — run: dotnet run --project userland/host/Xdos.Host -- codegen>");
        sb.AppendLine("namespace Xdos.Abstractions;");
        sb.AppendLine();
        sb.AppendLine("public static class ThemeTokens");
        sb.AppendLine("{");
        sb.AppendLine("    public const int ScreenColumns = 80;");
        sb.AppendLine("    public const int ScreenRows = 25;");
        sb.AppendLine("    public const string ShellPrompt = \"xdos> \";");
        sb.AppendLine("}");

        var outDir = Path.Combine(root, "userland", "host", "Xdos.Host", "Generated");
        Directory.CreateDirectory(outDir);
        var outPath = Path.Combine(outDir, "ThemeTokens.generated.cs");
        File.WriteAllText(outPath, sb.ToString());
        Console.WriteLine($"  wrote {Path.GetRelativePath(root, outPath)}");
    }

    static string Pascal(string snake) =>
        string.Concat(snake.Split('_', '-').Select(s => char.ToUpper(s[0]) + s[1..]));
}
